-- Implementation guide.
--
-- Integration contract:
-- Exactly seven application tables: users, quizzes, questions, attempts, answers, events,
-- results. Extra columns above support reload, deduplication, autosave ordering, and teacher
-- decisions without extra files.
--
-- Acceptance criteria:
-- A fresh schema blocks duplicate attempts/results/answers, invalid roles, orphan rows, and
-- repeated client event ids.
--
-- Implementation notes:
-- This file is SQL comments only. No CREATE statements are included. Store integrity score in
-- results; academic MCQ totals are separate response fields, never the same score.
--
-- Implementation steps:
-- 1. Create users with integer id, name, case normalized unique email, password_hash, role
--    constrained to student or teacher, and created_at.
-- 2. Create quizzes with id, teacher_id referencing users, title, instructions, positive
--    time_limit_min, and nullable due_at. Use UTC timestamps and reject invalid owner roles in
--    application validation.
-- 3. Create questions with id, quiz_id, sort_order, type constrained to mcq or short, prompt,
--    options_json, answer_key, and positive points. MCQ options use stable ids with text;
--    answer_key refers to an option id.
-- 4. Create attempts with id, quiz_id, student_id, started_at, deadline_at, nullable
--    submitted_at, and consent_given. Add UNIQUE(quiz_id, student_id) so a start retry cannot
--    create a second attempt.
-- 5. Create answers with id, attempt_id, question_id, response, nullable is_correct,
--    client_version, and updated_at. Add UNIQUE(attempt_id, question_id) for upsert and
--    ordered autosave. Short answer correctness stays null until a future grading policy
--    exists.
-- 6. Create events with id, attempt_id, nullable question_id, client_event_id, t_ms,
--    received_at, type, and meta_json. Add UNIQUE(attempt_id, client_event_id) so retries do
--    not duplicate evidence.
-- 7. Create results with id, UNIQUE attempt_id, score bounded 0 to 100, level, features_json,
--    flags_json, computed_at, decision, reviewed_by, and reviewed_at. Default decision to
--    pending and allow pending, cleared, and needs_follow_up.
-- 8. Add child foreign keys with intentional deletion rules and indexes on events(attempt_id,
--    t_ms) and attempts(quiz_id, student_id). Keep a nullable question event valid when
--    deleting a quiz by deleting its whole attempt tree together.
-- 9. Use IF NOT EXISTS for initial table/index creation. Document that this does not alter
--    existing columns: later schema changes need versioned migration steps in migrate.js.
-- 10. Enforce that an answer/event question belongs to the attempt quiz in controllers and
--     repository transactions; independent foreign keys alone do not prove that relationship.
